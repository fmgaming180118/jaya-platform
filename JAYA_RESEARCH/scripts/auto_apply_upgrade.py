# Storage file for applied upgrade history deduplication
HISTORY_FILE = os.path.join(RESEARCH_ROOT, "data", "applied_upgrades.json")


def load_applied_history() -> set:
    """Loads previously applied research finding IDs."""
    if os.path.exists(HISTORY_FILE):
        try:
            with open(HISTORY_FILE, "r", encoding="utf-8") as f:
                data = json.load(f)
                return set(data.get("applied_ids", []))
        except Exception:
            return set()
    return set()


def save_applied_history(applied_ids: set):
    """Saves applied research finding IDs to prevent duplicate processing."""
    os.makedirs(os.path.dirname(HISTORY_FILE), exist_ok=True)
    with open(HISTORY_FILE, "w", encoding="utf-8") as f:
        json.dump({"applied_ids": list(applied_ids), "last_updated": time.time()}, f, indent=2)


