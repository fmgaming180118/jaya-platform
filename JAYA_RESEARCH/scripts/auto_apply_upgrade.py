def run_autonomous_research_and_update():
    applied_ids = load_applied_history()
    
    # Find next unapplied research topic
    next_topic = None
    for item in RESEARCH_TOPIC_POOL:
        if item["id"] not in applied_ids:
            next_topic = item
            break

    if not next_topic:
        print("\n" + "=" * 70)
        print("ℹ️ STATUS: SEMUA PENELITIAN TERBARU SUDAH TERPASANG DI JAYA_CORE!")
        print("   Tidak ada update baru yang perlu diproses. Menunggu publikasi riset berikutnya...")
        print("=" * 70)
        return

    print("=" * 70)
    print("🔬 JAYA_RESEARCH AUTONOMOUS RESEARCH ENGINE RUNNING")
    print("=" * 70)
    
    finding = ResearchFinding(
        finding_id=next_topic["id"],
        paper_title=next_topic["title"],
        authors=next_topic["authors"],
        topic=next_topic["topic"],
        gap_summary=next_topic["gap"],
        suggested_patch_type=next_topic["patch_type"],
        patch_code=next_topic["code"],
        confidence_score=0.99
    )

    print(f"📌 Research Topic   : {finding.topic}")
    print(f"📄 Paper Title      : {finding.paper_title}")
    print(f"💡 Research Gap     : {finding.gap_summary}")
    print(f"🎯 Confidence Score : {finding.confidence_score * 100}%")

    print("\n" + "=" * 70)
    print("🌐 JAYA_RESEARCH TRANSMITTING UPGRADE TO JAYA_CORE")
    print("=" * 70)

    bridge = ResearchEcosystemBridge()
    result = bridge.submit_research_upgrade(finding)

    print("\n" + "=" * 70)
    print("✅ JAYA_CORE EVOLUTION GATE RESPONSE TO JAYA_RESEARCH")
    print("=" * 70)
    print(json.dumps(result, indent=2))

    if result.get("auto_deployed_by_research"):
        applied_ids.add(finding.finding_id)
        save_applied_history(applied_ids)
        print("\n🎉 SUCCESS: JAYA_RESEARCH HAS AUTONOMOUSLY DEPLOYED THE PATCH TO JAYA_CORE!")
        print(f"📁 Target File: {result.get('target_path')}")
    else:
        print("\n⚠️ DEPLOYMENT FAILED OR REJECTED BY EVOLUTION GATE.")
    print("=" * 70)


if __name__ == "__main__":
    import argparse
    parser = argparse.ArgumentParser(description="Autonomous JAYA_RESEARCH Auto-Upgrade Runner")
    parser.add_argument("--once", action="store_true", help="Run research update once and exit")
    parser.add_argument("--interval", type=int, default=60, help="Run background daemon loop every N seconds (default: 60s)")
    args = parser.parse_args()

    if args.once or args.interval <= 0:
        run_autonomous_research_and_update()
    else:
        print(f"🔄 JAYA_RESEARCH Continuous Auto-Upgrade Active (Scanning every {args.interval} seconds)")
        try:
            cycle = 1
            while True:
                print(f"\n⏰ [Cycle {cycle} - {time.strftime('%H:%M:%S')}] Scanning for new research papers and brain updates...")
                run_autonomous_research_and_update()
                print(f"\n💤 Cycle {cycle} complete. Waiting {args.interval}s for next continuous scan...")
                time.sleep(args.interval)
                cycle += 1
        except KeyboardInterrupt:
            print("\n🛑 Continuous autonomous upgrade loop stopped by user.")
